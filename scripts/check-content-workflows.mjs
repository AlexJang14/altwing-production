import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),yaml=require('js-yaml');
const read=p=>yaml.load(fs.readFileSync(p,'utf8'));
const wf=read('.github/workflows/content-intelligence.yml'),pages=read('.github/workflows/pages.yml'),validate=read('.github/workflows/domain-migration.yml');
assert.ok(wf.on.pull_request);
assert.ok(wf.jobs.collect.if.includes("github.event_name != 'pull_request'"));
assert.ok(wf.jobs.validation.steps.some(s=>s.run==='npm run test:content'));
assert.ok(wf.on.workflow_dispatch.inputs.dry_run.default===true);
assert.ok(wf.on.schedule.some(x=>x.cron==='17 6 * * 1'&&x.timezone==='America/New_York'));
assert.deepEqual(wf.on.schedule.map(x=>x.cron).sort(),['17 6 * * 1','37 5 * * *'].sort(),'Only verified daily/weekly cadences are scheduled at launch');
assert.ok(wf.on.schedule.every(x=>x.timezone==='America/New_York'));
const registry=JSON.parse(fs.readFileSync('content/intelligence/sources.json','utf8'));
assert.ok(registry.sources.filter(s=>s.adapter==='manual').every(s=>s.enabled===false));
assert.equal(registry.sources.find(s=>s.adapter==='scorecard').enabled,false,'Optional unverified Scorecard stays disabled');
assert.ok(wf.jobs.collect.if.includes('ALTWING_CONTENT_AUTOMATION_ENABLED'));
assert.ok(wf.jobs.publish.if.includes('ALTWING_CONTENT_PUBLISH_ENABLED'));
assert.ok(wf.jobs.pages.uses==='./.github/workflows/pages.yml');
assert.ok(wf.jobs.pages.with.ref.includes('needs.publish.outputs.sha'));
assert.ok(pages.on.workflow_call.inputs.ref&&validate.on.workflow_call.inputs.ref);
assert.ok(pages.jobs.validate.with.ref.includes('inputs.ref'));
assert.ok(pages.jobs.build.steps[0].with.ref.includes('inputs.ref'));
assert.ok(validate.jobs.validate.steps[0].with.ref.includes('inputs.ref'));
assert.equal(wf.jobs.collect.permissions?.contents??wf.permissions.contents,'read');
const text=fs.readFileSync('.github/workflows/content-intelligence.yml','utf8');
assert.ok(!text.includes('secrets: inherit')&&!text.includes('ANALYTICS_')&&!text.includes('wrangler')&&!text.includes('--force'));
assert.ok(text.includes('git add content/intelligence/'));
console.log('PASS: Monday 06:17 America/New_York, default dry-run and two activation gates, exact-SHA validation/Pages handoff, public-only permissions, no reliance on token-triggered push workflows. This is local configuration validation, not a remotely executed Actions run.');
